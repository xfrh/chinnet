using System.Text.RegularExpressions;

namespace ManageSystem.Core.Utility
{
    /// <summary>
    /// 操作正则表达式的公共类
    /// </summary>    
    public class RegexHelper
    {
        #region 验证输入字符串是否与模式字符串匹配
        /// <summary>
        /// 验证输入字符串是否与模式字符串匹配，匹配返回true
        /// </summary>
        /// <param name="input">输入字符串</param>
        /// <param name="pattern">模式字符串</param>        
        public static bool IsMatch(string input, string pattern)
        {
            return IsMatch(input, pattern, RegexOptions.IgnoreCase);
        }

        /// <summary>
        /// 验证输入字符串是否与模式字符串匹配，匹配返回true
        /// </summary>
        /// <param name="input">输入的字符串</param>
        /// <param name="pattern">模式字符串</param>
        /// <param name="options">筛选条件</param>
        public static bool IsMatch(string input, string pattern, RegexOptions options)
        {
            return Regex.IsMatch(input, pattern, options);
        }

        /// <summary>
        /// 是否是手机号码
        /// </summary>
        /// <param name="vlaue"></param>
        /// <returns></returns>
        public static bool IsPhone(string vlaue)
        {
            return   new Regex(@"^[1]{1}[0-9]{10}$").IsMatch(vlaue) ;
        }

        /// <summary>
        /// 是否是邮箱地址
        /// </summary>
        /// <param name="vlaue"></param>
        /// <returns></returns>
        public static bool IsEmail(string vlaue)
        {
            return new Regex(@"^[a-zA-Z0-9.!#$%&'*+\/=?^_`{|}~-]+@[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?(?:\.[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)*$").IsMatch(vlaue);
        }

        #endregion
    }
}
